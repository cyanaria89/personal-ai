def test_no_progress_graph_skips_selected_downstream_agents_and_keeps_final_fail():
    state = db_state(required_agents=["db", "backend", "frontend"])
    db = LocalLlmDouble(DDL, DDL)
    backend, frontend = LocalLlmDouble(), LocalLlmDouble()
    pm = LocalLlmDouble(valid_pm_plan('db', 'backend', 'frontend'))
    review = LocalLlmDouble(json.dumps({"status": "PASS", "issues": []}))
    with patch.object(nodes, "db_llm", db), patch.object(nodes, "pm_llm", pm), \
         patch.object(nodes, "review_llm", review), patch.object(nodes, "backend_llm", backend), \
         patch.object(nodes, "frontend_llm", frontend), patch.object(nodes, "search_db_context", return_value=[]):
        result = create_workflow().invoke(state)
    assert result["required_agents"] == ["db", "backend", "frontend"]
    assert result["db_fix_count"] == 1
    assert result["db_validation"]["fix"]["status"] == "NO_PROGRESS"
    assert len(db.prompts) == 2
    assert not backend.prompts and not frontend.prompts
    assert result["review_status"] == "FAIL"
    assert result["final_result"].splitlines()[-1] == "FAIL"
