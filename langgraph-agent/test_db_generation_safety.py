@pytest.mark.parametrize("outputs,expected_fixes,expected_status", [
    ((DDL, DDL), 1, "NO_PROGRESS"),
    ((DDL, DDL + "\n보충1", DDL + "\n보충2"), 2, "CHANGED"),
    ((DDL, DDL + "\n\n" + QUERY), 1, "SUCCEEDED"),
])
def test_graph_finishes_with_real_validators_and_bounded_db_fixes(outputs, expected_fixes, expected_status):
    state = db_state()
    db = LocalLlmDouble(*outputs)
    pm = LocalLlmDouble(valid_pm_plan('db'))
    review = LocalLlmDouble(json.dumps({"status": "PASS", "issues": [], "summary": "ok"}))
    with patch.object(nodes, "db_llm", db), patch.object(nodes, "pm_llm", pm), \
         patch.object(nodes, "review_llm", review), patch.object(nodes, "search_db_context", return_value=[]):
        app = create_workflow()
        for update in app.stream(state, stream_mode="updates"):
            for delta in update.values():
                state.update(delta)
    assert len(db.prompts) == expected_fixes + 1
    assert len(pm.prompts) == len(review.prompts) == 1
    assert state["db_fix_count"] == expected_fixes <= 2
    assert state["db_validation"]["fix"]["status"] == expected_status
    expected_final = "PASS" if expected_status == "SUCCEEDED" else "FAIL"
    assert state["review_status"] == expected_final
    assert state["final_result"].splitlines()[-1] == expected_final


