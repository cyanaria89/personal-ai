DDL = """## Design
메모의 title과 content를 보존한다.

## DDL
```sql
CREATE TABLE memo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    content VARCHAR(2000) NOT NULL
);
```"""
QUERY = "## Queries\n```sql\nSELECT id, title, content FROM memo ORDER BY id DESC;\n```"
REQUEST = "PostgreSQL memo 테이블을 생성하고 목록 조회 SELECT SQL을 작성해줘."


class LocalLlmDouble:
    """실제 invoke_agent의 metadata 경로까지 검사하되 네트워크는 호출하지 않는다."""
    model = "qwen2.5-coder:14b"
    num_ctx = 10240
    num_predict = 2048

    def __init__(self, *outputs):
        self.outputs = iter(outputs)
        self.prompts = []

    def invoke(self, messages):
        self.prompts.append((messages[0].content, messages[1].content))
        return SimpleNamespace(content=next(self.outputs), response_metadata={"done_reason": "stop"})


def db_state(request=REQUEST, required_agents=None):
    state = full_state(nodes.empty_project_context())
    state.update(user_request=request, project_root="", project_plan="DB 계약을 따른다.",
                 required_agents=required_agents or ["db"], db_result="",
                 db_validation={"status": "NOT_RUN", "issues": []}, db_fix_count=0,
                 backend_result="", frontend_result="")
    return state


def generate_and_validate(state, model):
    with patch.object(nodes, "db_llm", model), patch.object(nodes, "search_db_context", return_value=[]):
        state.update(nodes.db_agent(state))
    state.update(nodes.db_validator(state))


@pytest.mark.parametrize("user_request,output", [
    ("memo 테이블을 생성해줘", DDL),
    ("memo 목록 조회 SELECT SQL을 작성해줘", QUERY),
    (REQUEST, DDL + "\n\n" + QUERY),
])
@pytest.mark.parametrize("backend", [False, True])
def test_sql_contract_allows_requested_sql_without_forcing_other_work(user_request, output, backend):
    state = db_state(user_request, ["db", "backend"] if backend else ["db"])
    model = LocalLlmDouble(output)
    generate_and_validate(state, model)
    system, user = model.prompts[0]
    assert "## Queries" in system and "## Queries" in user
    assert "DDL-only 요청에 불필요한 SELECT" in system
    assert "DDL-only 요청에 불필요한 SELECT" in user
    assert "SELECT-only 요청에 DDL" in user
    assert "SQL DDL, 최소 Backend Handoff까지만" not in user
    assert "Backend 구현은 절대 작성하지 마세요" in user
    assert "Entity, Repository, Service, Controller, DTO" in system
    assert state["db_validation"]["status"] == "PASS"
    assert state["db_fix_count"] == 0
    if not backend:
        assert "Backend 관련 섹션을 절대 출력하지 마세요" in user


def test_fix_handoff_preserves_full_ddl_and_adds_required_select_with_context_metrics():
    state = db_state()
    model = LocalLlmDouble(DDL, DDL + "\n\n" + QUERY)
    generate_and_validate(state, model)
    assert state["db_validation"]["issues"][0]["rule"] == "MISSING_SELECT"
    prior = copy.deepcopy(state)
    generate_and_validate(state, model)
    system, user = model.prompts[1]
    assert prior["db_result"] in user
    issue_text = user.split("[현재 미해결 DB Validator Issue]\n", 1)[1]
    assert json.JSONDecoder().raw_decode(issue_text)[0] == prior["db_validation"]["issues"]
    assert "정상 SQL·설계·제약조건·Handoff를 보존" in user
    assert "전체 DB 산출물을 다시 작성" in user
    assert state["db_result"].startswith(DDL)
    assert state["db_validation"]["status"] == "PASS"
    assert state["db_validation"]["fix"]["status"] == "SUCCEEDED"
    assert state["db_fix_count"] == 1
    assert route_after_db(state) == "review"
    metric = state["llm_metrics"][-1]["db_prompt_context"]
    count, kind = prompt_counter(model.model)
    assert metric["counter"] == kind
    assert metric["prompt_tokens"] == count(system, user)
    assert metric["previous_result_added_tokens"] > 0
    assert metric["remaining_tokens"] == model.num_ctx - model.num_predict - 256 - count(system, user)
    assert (metric["context_size"], metric["reserved_output_tokens"]) == (10240, 2048)
    assert prior["db_validation"]["status"] == "FAIL"


def test_fix_that_drops_normal_ddl_cannot_pass_mixed_contract():
    state = db_state()
    model = LocalLlmDouble(DDL, QUERY)
    generate_and_validate(state, model)
    generate_and_validate(state, model)
    assert DDL in model.prompts[1][1]
    assert state["db_validation"]["status"] == "FAIL"
    assert "MISSING_CREATE_TABLE" in {i["rule"] for i in state["db_validation"]["issues"]}
    assert state["db_validation"]["fix"]["status"] == "CHANGED"


def test_fix_uses_immediately_previous_output_and_does_not_mutate_input_state():
    state = db_state()
    changed = DDL + "\n\n## Notes\n정상 부분 보존"  # SQL 자체는 동일한 변경 결과
    model = LocalLlmDouble(DDL, changed, DDL + "\n\n" + QUERY)
    generate_and_validate(state, model)
    generate_and_validate(state, model)
    assert state["db_validation"]["fix"]["status"] == "CHANGED"
    before = copy.deepcopy(state)
    with patch.object(nodes, "db_llm", model), patch.object(nodes, "search_db_context", return_value=[]):
        update = nodes.db_agent(state)
    assert state == before
    assert changed in model.prompts[2][1]
    assert model.prompts[2][1].count("[직전 DB Agent 전체 산출물 — 수정 대상 데이터]") == 1
    state.update(update)
    state.update(nodes.db_validator(state))
    assert state["db_validation"]["status"] == "PASS"
    assert state["db_fix_count"] == 2


def test_same_failure_records_no_progress_and_stops_before_limit():
    state = db_state()
    model = LocalLlmDouble(DDL, DDL)
    generate_and_validate(state, model)
    issues = copy.deepcopy(state["db_validation"]["issues"])
    generate_and_validate(state, model)
    assert state["db_validation"]["status"] == "FAIL"
    assert state["db_validation"]["issues"] == issues
    assert state["db_validation"]["fix"]["status"] == "NO_PROGRESS"
    assert state["db_fix_count"] == 1 < get_max_agent_fix_count()
    assert route_after_db(state) == "review"
    state["review_status"] = "PASS"
    assert nodes.final_agent(state)["final_result"].splitlines()[-1] == "FAIL"


def test_issue_order_does_not_hide_same_failure():
    state = db_state()
    model = LocalLlmDouble("설계만 작성", "설계만 작성")
    generate_and_validate(state, model)
    state["db_validation"]["issues"].reverse()
    generate_and_validate(state, model)
    assert state["db_validation"]["fix"]["status"] == "NO_PROGRESS"


def test_same_output_with_changed_issues_is_not_no_progress():
    state = db_state()
    model = LocalLlmDouble(DDL, DDL)
    generate_and_validate(state, model)
    state["db_validation"]["issues"].append({"rule": "OLD_ISSUE", "message": "이전 이슈"})
    generate_and_validate(state, model)
    assert state["db_validation"]["status"] == "FAIL"
    assert state["db_validation"]["fix"]["status"] == "CHANGED"
    assert route_after_db(state) == "db"


def test_same_output_that_now_validates_successfully_is_not_blocked():
    state = db_state("memo 테이블을 생성해줘")
    state.update(db_result=DDL, db_validation={"status": "FAIL", "issues": [{"rule": "OLD_ISSUE"}]})
